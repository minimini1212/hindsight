package io.hindsight.core.brain;

/**
 * 🔴 <b>한 기록에 얼마나 매달릴 것인가.</b> 시도 횟수와 돈, 둘 다 끊는다.
 *
 * <h2>왜 둘 다인가 — 하나만 끊으면 안 끊긴다</h2>
 * <pre>
 *   횟수만 끊으면 │ 3번째 시도가 40만 토큰짜리일 수 있다. 상한이 사실상 없다
 *   돈만 끊으면   │ 싼 모델로 200번 돌 수 있다. 200번 실패한 것은 못 고치는 것이다
 * </pre>
 *
 * <h2>🔴 「예산을 다 썼다」는 실패가 아니다</h2>
 * 예산이 끝난 것과 패치가 틀린 것은 <b>다른 사실</b>이다. 같게 다루면
 * 「LLM 이 못 고쳤다」는 결론이 나오는데, 실제로는 <b>한 번도 제대로 못 시켜 본 것</b>일 수 있다.
 * 그래서 {@link 남은것#왜} 가 둘을 구별해서 말한다.
 *
 * <h2>이 클래스는 무엇을 «안» 하나</h2>
 * 🔴 <b>LLM 을 부르지 않는다. 돈을 세지도 않는다</b> — 쓴 만큼을 밖에서 받아 적을 뿐이다.
 * 그래서 이 판단은 API 키 없이 전수로 시험된다. 부르는 코드와 끊는 코드를 섞으면
 * 「상한이 진짜로 끊나」를 확인하려고 매번 진짜 돈을 써야 한다.
 */
public final class AttemptBudget {

    /**
     * 기본 시도 횟수. 🔴 <b>3이다.</b> 설계가 정한 값이고, 그 뒤는 사람의 문제다.
     * 세 번 다른 답을 내고도 안 되면 네 번째가 될 이유가 별로 없다.
     */
    public static final int 기본_시도_횟수 = 3;

    /** 기본 비용 상한. 기록 하나에 <b>1달러</b>. 설계 §7-4. */
    public static final long 기본_상한_센트 = 100L;

    private final int 시도_상한;
    private final long 비용_상한_센트;

    private int 쓴_시도 = 0;
    private long 쓴_센트 = 0;

    public AttemptBudget() {
        this(기본_시도_횟수, 기본_상한_센트);
    }

    /**
     * @param 시도_상한     1 이상
     * @param 비용_상한_센트 0 이상. 🔴 <b>0 은 「공짜만 허용」이지 「무제한」이 아니다</b> —
     *                      무제한을 두면 설정 실수 하나가 청구서가 된다
     */
    public AttemptBudget(int 시도_상한, long 비용_상한_센트) {
        if (시도_상한 < 1) {
            throw new IllegalArgumentException("시도 상한은 1 이상이어야 한다: " + 시도_상한);
        }
        if (비용_상한_센트 < 0) {
            throw new IllegalArgumentException("비용 상한은 0 이상이어야 한다: " + 비용_상한_센트);
        }
        this.시도_상한 = 시도_상한;
        this.비용_상한_센트 = 비용_상한_센트;
    }

    /**
     * 한 번 더 시켜도 되나.
     *
     * @param 다음에_들_것으로_보이는_센트 이번 호출에 들 것으로 «보이는» 값.
     *        🔴 <b>음수는 「모른다」다.</b> 모를 때 0 으로 치면 상한이 없는 것과 같아진다 —
     *        그래서 모르면 <b>거절한다</b>
     */
    public 남은것 한번_더_되나(long 다음에_들_것으로_보이는_센트) {
        if (쓴_시도 >= 시도_상한) {
            return 남은것.끝(("시도 %d번을 다 썼다. 🔴 이건 「못 고쳤다」가 아니라 "
                    + "「여기까지만 해 보기로 했다」다").formatted(시도_상한));
        }
        if (다음에_들_것으로_보이는_센트 < 0) {
            return 남은것.끝("다음 호출에 얼마가 들지 «모른다». 모르는 값을 0 으로 치면 "
                    + "상한이 없는 것과 같으므로 여기서 멈춘다");
        }
        long 쓰게_될_것 = 쓴_센트 + 다음에_들_것으로_보이는_센트;
        if (쓰게_될_것 > 비용_상한_센트) {
            return 남은것.끝(("비용 상한을 넘는다: 이미 %d센트 썼고 이번에 %d센트가 더 들어 "
                    + "%d센트가 되는데 상한은 %d센트다").formatted(
                    쓴_센트, 다음에_들_것으로_보이는_센트, 쓰게_될_것, 비용_상한_센트));
        }
        return 남은것.된다(시도_상한 - 쓴_시도, 비용_상한_센트 - 쓴_센트);
    }

    /**
     * 실제로 한 번 썼다고 적는다.
     *
     * <p>🔴 <b>「부르기 전」이 아니라 「부른 뒤」에 부른다.</b> 부르기 전에 세면,
     * 호출이 터져서 답을 못 받았을 때도 시도를 하나 깎는다 — 그러면 네트워크가 나쁜 날
     * LLM 을 «한 번도» 못 불러 보고 「세 번 실패」가 된다.
     *
     * @param 실제로_든_센트 음수면 「모른다」. 🔴 그때는 <b>상한만큼 쓴 것으로 친다</b> —
     *        모르는 비용을 0 으로 적으면 예산이 영영 안 준다
     */
    public void 한번_썼다(long 실제로_든_센트) {
        쓴_시도++;
        쓴_센트 += 실제로_든_센트 < 0 ? 비용_상한_센트 : 실제로_든_센트;
    }

    public int 쓴_시도() {
        return 쓴_시도;
    }

    public long 쓴_센트() {
        return 쓴_센트;
    }

    /** 사람이 읽는 한 줄. PR 본문에 그대로 나간다. */
    public String describe() {
        return "시도 %d/%d · 비용 %d/%d센트".formatted(쓴_시도, 시도_상한, 쓴_센트, 비용_상한_센트);
    }

    /**
     * @param 되나        한 번 더 시켜도 되나
     * @param 남은_시도   🔴 안 될 때는 {@code -1} 이 아니라 0 이다. 「모른다」가 아니라 「없다」다
     * @param 남은_센트   같다
     * @param 왜          🔴 안 될 때 <b>왜 안 되는지.</b> 이게 없으면 PR 에
     *                    「세 번 실패」라고만 적히고, 실제로 세 번 시켰는지 알 수 없다
     */
    public record 남은것(boolean 되나, int 남은_시도, long 남은_센트, String 왜) {

        static 남은것 된다(int 남은_시도, long 남은_센트) {
            return new 남은것(true, 남은_시도, 남은_센트, null);
        }

        static 남은것 끝(String 왜) {
            return new 남은것(false, 0, 0, 왜);
        }
    }
}
