package io.hindsight.core.replay;

import io.hindsight.model.ReplayInfo;

/**
 * 기록 시점의 DB 상태를 떠 두었다가 재생 전에 되돌린다.
 *
 * <h2>🔴 재생은 요청을 다시 보내는 게 아니다. «되돌린 자리»에서 다시 보내는 것이다</h2>
 * 되돌리지 않으면 같은 요청이 다른 답을 낸다 — 그리고 그 차이는 <b>패치가 만든 것이 아니라
 * 우리가 만든 것</b>이다. 축은 「읽기냐 쓰기냐」가 아니라 <b>「되돌렸나」</b>다.
 * 되돌리지 않으면 읽기 요청도 갈라진다(그 사이 다른 요청이 DB 를 바꿨으면 목록이 달라진다).
 *
 * <h2>🔴 되돌릴 목록을 «나열하지» 않는다</h2>
 * 2026-09-11 에 후보 셋을 갈라서 재고 <b>스냅숏</b>으로 정했다. 고른 이유는 속도가 아니라
 * <b>되돌릴 목록을 몰라도 된다</b>는 것이다.
 *
 * <pre>
 *   트랜잭션 롤백   🔴 행은 돌아오는데 「다음 id 는 몇 번」이 안 돌아온다
 *                     → 재생 두 번이 id 4·5·6 으로 갈린다. 결정론이 아니다
 *   가짜 DB        🔴 정석 수정이 보낸 질의가 기록에 없다 → 채점 불가만 남는다
 *   스냅숏         ✅ 행과 카운터가 «같이» 돌아온다
 * </pre>
 *
 * <p>나열해서 원복하는 코드는 앱마다 다른 목록에서 한 항목을 빠뜨리고, 그 순간
 * <b>부분 복원</b>이 된다. 🔴 <b>부분 복원은 무복원보다 위험하다</b> — 무복원은 답이 다르게
 * 나와서 눈에 띄지만, 부분 복원은 재생이 죽고 채점기가 그 죽음을
 * <b>「패치가 못 고쳤다」로 읽는다.</b> 패치는 아무 잘못이 없는데 LLM 이 벌을 받는다.
 */
public interface StateSnapshot {

    /** 지금 상태를 떠 둔다. 기록을 만들기 «전»에 부른다. */
    Handle take();

    /** 떠 둔 상태 하나. 다 쓰면 {@link #close()} 로 임시 자원을 지운다. */
    interface Handle extends AutoCloseable {

        /**
         * 되돌리고, <b>어디까지 되돌아왔는지 «확인해서»</b> 돌려준다.
         *
         * <h2>🔴 「되돌렸다」와 「되돌렸다고 친다」는 다르다</h2>
         * 되돌리는 명령을 보냈다고 해서 되돌아온 것이 아니다. 그래서 이 메서드는
         * 되돌린 «뒤에» DB 에게 다시 물어보고, <b>확인된 것만</b> {@code true} 로 적는다.
         *
         * <table>
         *   <tr><th>값</th><th>뜻</th></tr>
         *   <tr><td>{@code true}</td><td>되돌렸고, 되돌아온 것을 «확인했다»</td></tr>
         *   <tr><td>{@code false}</td><td>🔴 보았고 못 되돌렸다 → 등급 {@code PARTIAL}</td></tr>
         *   <tr><td>{@code null}</td><td>🔴 «안 봤다». {@code false} 와 다른 사실이다</td></tr>
         * </table>
         */
        ReplayInfo.StateRestore restoreAndVerify();

        @Override
        void close();
    }
}
